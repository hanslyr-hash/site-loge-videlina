@app.context_processor
def inject_notifications():
    """
    Rend les notifications disponibles dans tous les templates
    des membres.
    """

    if "member_id" not in session:
        return {
            "notifications": [],
            "unread_count": 0,
            "unread_notifications_count": 0,
        }

    database = db()

    notifications = database.execute(
        """
        SELECT
            id,
            message,
            created_at,
            is_read
        FROM notifications
        WHERE member_id = %s
        ORDER BY created_at DESC
        LIMIT 10
        """,
        (session["member_id"],),
    ).fetchall()

    result = database.execute(
        """
        SELECT COUNT(*) AS count
        FROM notifications
        WHERE member_id = %s
          AND is_read = FALSE
        """,
        (session["member_id"],),
    ).fetchone()

    unread_count = result["count"] if result else 0

    return {
        "notifications": notifications,

        # Nom utilisé éventuellement par les templates
        "unread_count": unread_count,

        # Nom actuellement utilisé par base_member.html
        "unread_notifications_count": unread_count,
    }



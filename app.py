@app.route("/mot-de-passe", methods=["GET", "POST"])
@login_required
def change_password():

    if request.method == "POST":

        ancien_mot_de_passe = request.form.get(
            "ancien_mot_de_passe",
            ""
        )

        nouveau_mot_de_passe = request.form.get(
            "nouveau_mot_de_passe",
            ""
        )

        confirmation = request.form.get(
            "confirmation",
            ""
        )

        # Récupération du membre connecté
        member = db().execute(
            """
            SELECT password_hash
            FROM members
            WHERE id = %s
            """,
            (session["member_id"],)
        ).fetchone()

        if not member:
            flash(
                "Membre introuvable.",
                "error"
            )

            return redirect(
                url_for("dashboard")
            )

        # Vérification de l'ancien mot de passe
        if not check_password_hash(
            member["password_hash"],
            ancien_mot_de_passe
        ):
            flash(
                "Votre ancien mot de passe est incorrect.",
                "error"
            )

            return render_template(
                "change_password.html"
            )

        # Vérification de la longueur
        if len(nouveau_mot_de_passe) < 8:
            flash(
                "Le nouveau mot de passe doit contenir au moins 8 caractères.",
                "error"
            )

            return render_template(
                "change_password.html"
            )

        # Vérification de la confirmation
        if nouveau_mot_de_passe != confirmation:
            flash(
                "Les deux nouveaux mots de passe ne correspondent pas.",
                "error"
            )

            return render_template(
                "change_password.html"
            )

        # Nouveau hash sécurisé
        nouveau_hash = generate_password_hash(
            nouveau_mot_de_passe
        )

        db().execute(
            """
            UPDATE members
            SET password_hash = %s
            WHERE id = %s
            """,
            (
                nouveau_hash,
                session["member_id"]
            )
        )

        db().commit()

        flash(
            "Votre mot de passe a été modifié avec succès.",
            "success"
        )

        return redirect(
            url_for("dashboard")
        )

    return render_template(
        "change_password.html"
    )


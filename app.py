@app.route(
    "/bibliotheque",
    methods=["GET", "POST"]
)
@login_required
def library():

    database = db()

    # =====================================================
    # AJOUT D'UN OUVRAGE
    # =====================================================

    if request.method == "POST":

        if not is_admin():

            flash(
                "Seuls les administrateurs peuvent ajouter des ouvrages.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        if not supabase_is_configured():

            flash(
                "Le stockage Supabase n'est pas configuré.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        uploaded = request.files.get(
            "file"
        )

        title = request.form.get(
            "title",
            "",
        ).strip()

        author = request.form.get(
            "author",
            "",
        ).strip()

        category = request.form.get(
            "category",
            "",
        ).strip()

        description = request.form.get(
            "description",
            "",
        ).strip()

        access_grade = request.form.get(
            "access_grade",
            "Apprenti",
        ).strip()

        # -------------------------------------------------
        # VALIDATION DU GRADE
        # -------------------------------------------------

        if access_grade not in ALLOWED_GRADES:

            flash(
                "Niveau d'accès invalide.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        # -------------------------------------------------
        # VALIDATION
        # -------------------------------------------------

        if not title or not category:

            flash(
                "Le titre et la catégorie sont obligatoires.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        if not uploaded or not uploaded.filename:

            flash(
                "Veuillez sélectionner un fichier.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        original_name = secure_filename(
            uploaded.filename
        )

        if (
            not original_name
            or "." not in original_name
        ):

            flash(
                "Nom de fichier invalide.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        extension = (
            original_name
            .rsplit(".", 1)[-1]
            .lower()
        )

        if extension not in ALLOWED_LIBRARY_EXTENSIONS:

            flash(
                "Format non autorisé. Utilisez uniquement PDF ou EPUB.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        # -------------------------------------------------
        # NOM UNIQUE
        # -------------------------------------------------

        stored_name = (
            f"{uuid.uuid4().hex}.{extension}"
        )

        try:

            uploaded.stream.seek(0)

            file_data = uploaded.read()

            if not file_data:

                flash(
                    "Le fichier envoyé est vide.",
                    "error",
                )

                return redirect(
                    url_for("library")
                )

            content_type = library_content_type(
                extension
            )

            storage_url = get_storage_url(
                stored_name
            )

            headers = get_storage_headers()

            headers["Content-Type"] = (
                content_type
            )

            # -------------------------------------------------
            # UPLOAD SUPABASE
            # -------------------------------------------------

            response = httpx.post(
                storage_url,
                headers=headers,
                content=file_data,
                timeout=120.0,
            )

            if response.status_code not in (
                200,
                201,
            ):

                app.logger.error(
                    "Supabase upload %s : %s",
                    response.status_code,
                    response.text[:500],
                )

                flash(
                    "Impossible d'envoyer le fichier vers Supabase.",
                    "error",
                )

                return redirect(
                    url_for("library")
                )

            # -------------------------------------------------
            # ENREGISTREMENT POSTGRESQL
            # -------------------------------------------------

            try:

                database.execute(
                    """
                    INSERT INTO library_items
                    (
                        title,
                        author,
                        category,
                        description,
                        stored_name,
                        original_name,
                        file_extension,
                        access_grade
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        title,
                        author,
                        category,
                        description,
                        stored_name,
                        original_name,
                        extension,
                        access_grade,
                    ),
                )

                database.commit()

            except Exception:

                database.rollback()

                # Supprimer le fichier de Supabase
                # si PostgreSQL échoue.

                try:

                    httpx.delete(
                        storage_url,
                        headers=get_storage_headers(),
                        timeout=30.0,
                    )

                except Exception:

                    app.logger.exception(
                        "Impossible de supprimer le fichier Supabase après échec PostgreSQL."
                    )

                raise

            flash(
                "Ouvrage ajouté avec succès.",
                "success",
            )

        except Exception:

            app.logger.exception(
                "Erreur lors de l'ajout de l'ouvrage."
            )

            flash(
                "Une erreur est survenue lors de l'ajout de l'ouvrage.",
                "error",
            )

        return redirect(
            url_for("library")
        )

    # =====================================================
    # RECHERCHE
    # =====================================================

    search = request.args.get(
        "q",
        "",
    ).strip()

    if search:

        pattern = f"%{search}%"

        items = database.execute(
            """
            SELECT *
            FROM library_items
            WHERE
                title ILIKE %s
                OR author ILIKE %s
                OR category ILIKE %s
                OR description ILIKE %s
            ORDER BY added_at DESC
            """,
            (
                pattern,
                pattern,
                pattern,
                pattern,
            ),
        ).fetchall()

    else:

        items = database.execute(
            """
            SELECT *
            FROM library_items
            ORDER BY added_at DESC
            """
        ).fetchall()

    return render_template(
        "library.html",
        items=items,
        search=search,
    )



@app.get("/bibliotheque/lire/<int:item_id>")
@login_required
def read_library_item(item_id):

    database = db()

    item = database.execute(
        """
        SELECT *
        FROM library_items
        WHERE id = %s
        """,
        (item_id,)
    ).fetchone()

    if item is None:

        flash(
            "Ouvrage introuvable.",
            "error"
        )

        return redirect(
            url_for("library")
        )

    # =====================================================
    # GRADE DU MEMBRE CONNECTÉ
    # =====================================================

    member = database.execute(
        """
        SELECT grade, role
        FROM members
        WHERE id = %s
        """,
        (session["member_id"],)
    ).fetchone()

    if member is None:

        flash(
            "Membre introuvable.",
            "error"
        )

        return redirect(
            url_for("library")
        )

    # =====================================================
    # HIÉRARCHIE DES GRADES
    # =====================================================

    grade_levels = {
        "Apprenti": 1,
        "Compagnon": 2,
        "Maître": 3,
        "Maître Secret": 4,
        "Grand Elu, Parfait et Sublime Macon": 5,
        "Chevalier Rose-Croix": 6,
        "CKS": 7
    }

    member_grade = (
        member["grade"] or "Apprenti"
    ).strip()

    required_grade = (
        item["access_grade"] or "Apprenti"
    ).strip()

    # =====================================================
    # ADMINISTRATEUR = ACCÈS COMPLET
    # =====================================================

    if member["role"] != "Administrateur":

        member_level = grade_levels.get(
            member_grade,
            0
        )

        required_level = grade_levels.get(
            required_grade,
            999
        )

        if member_level < required_level:

            flash(
                "Cet ouvrage est réservé à un grade supérieur.",
                "error"
            )

            return redirect(
                url_for("library")
            )

    # =====================================================
    # AUTORISÉ
    # =====================================================

    return render_template(
        "library_reader.html",
        item=item
    )


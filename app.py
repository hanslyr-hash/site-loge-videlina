@app.route(
    "/connexion",
    methods=["GET", "POST"]
)
def login():

    total = db().execute(
        """
        SELECT COUNT(*) AS total
        FROM members
        """
    ).fetchone()["total"]

    if not total:

        return redirect(
            url_for("setup")
        )

    if request.method == "POST":

        email = request.form.get(
            "email",
            "",
        ).strip().lower()

        password = request.form.get(
            "password",
            "",
        )

        member = db().execute(
            """
            SELECT *
            FROM members
            WHERE email = %s
            """,
            (email,),
        ).fetchone()

        if (
            member
            and member["status"] == "Actif"
            and check_password_hash(
                member["password_hash"],
                password,
            )
        ):

            session.clear()

            session.update(
                member_id=member["id"],
                member_name=member["name"],
                member_role=member["role"],
            )

            return redirect(
                url_for("dashboard")
            )

        flash(
            "Adresse e-mail, mot de passe incorrect ou compte inactif.",
            "error",
        )

    return render_template(
        "login.html"
    )



# =========================================================

@app.route(
    "/mot-de-passe-reinitialiser/<token>",
    methods=["GET", "POST"]
)
def reset_password(token):

    database = db()

    # Calculer l'empreinte du token reçu.
    token_hash = hashlib.sha256(
        token.encode("utf-8")
    ).hexdigest()

    reset_request = database.execute(
        """
        SELECT
            prt.id,
            prt.member_id,
            prt.expires_at,
            prt.used_at,
            m.name,
            m.email
        FROM password_reset_tokens prt
        JOIN members m
            ON m.id = prt.member_id
        WHERE prt.token_hash = %s
        """,
        (token_hash,),
    ).fetchone()

    # Token inexistant
    if not reset_request:

        flash(
            "Ce lien de réinitialisation est invalide.",
            "error",
        )

        return redirect(
            url_for("login")
        )

    # Token déjà utilisé
    if reset_request["used_at"] is not None:

        flash(
            "Ce lien de réinitialisation a déjà été utilisé.",
            "error",
        )

        return redirect(
            url_for("login")
        )

    # Token expiré
    if reset_request["expires_at"] <= datetime.now():

        flash(
            "Ce lien de réinitialisation a expiré.",
            "error",
        )

        return redirect(
            url_for("forgot_password")
        )

    if request.method == "POST":

        new_password = request.form.get(
            "nouveau_mot_de_passe",
            "",
        )

        confirmation = request.form.get(
            "confirmation",
            "",
        )

        # Vérification de la longueur
        if len(new_password) < 8:

            flash(
                "Le nouveau mot de passe doit contenir au moins 8 caractères.",
                "error",
            )

            return render_template(
                "reset_password.html"
            )

        # Vérification de la confirmation
        if new_password != confirmation:

            flash(
                "Les deux nouveaux mots de passe ne correspondent pas.",
                "error",
            )

            return render_template(
                "reset_password.html"
            )

        # Nouveau hash
        new_password_hash = generate_password_hash(
            new_password
        )

        try:

            # Modifier le mot de passe
            database.execute(
                """
                UPDATE members
                SET password_hash = %s
                WHERE id = %s
                """,
                (
                    new_password_hash,
                    reset_request["member_id"],
                ),
            )

            # Invalider immédiatement le token
            database.execute(
                """
                UPDATE password_reset_tokens
                SET used_at = CURRENT_TIMESTAMP
                WHERE id = %s
                """,
                (
                    reset_request["id"],
                ),
            )

            database.commit()

        except Exception:

            database.rollback()

            app.logger.exception(
                "Erreur lors de la réinitialisation du mot de passe."
            )

            flash(
                "Impossible de réinitialiser le mot de passe.",
                "error",
            )

            return render_template(
                "reset_password.html"
            )

        flash(
            "Votre mot de passe a été réinitialisé avec succès.",
            "success",
        )

        return redirect(
            url_for("login")
        )

    return render_template(
        "reset_password.html"
    )


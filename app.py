def is_admin():

    return (
        session.get("member_role")
        == "Administrateur"
    )


def get_member_grade_level(grade):

    return GRADE_LEVELS.get(
        (grade or "Apprenti").strip(),
        0,
    )


def has_library_access(
    member,
    required_grade,
):

    # Administrateur = accès complet
    if member["role"] == "Administrateur":
        return True

    member_level = get_member_grade_level(
        member["grade"]
    )

    required_level = GRADE_LEVELS.get(
        (required_grade or "Apprenti").strip(),
        999,
    )

    return member_level >= required_level



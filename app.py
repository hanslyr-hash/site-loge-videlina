@app.route(
    "/bibliotheque",
    methods=["GET", "POST"]
)
@login_required
def library():

    if request.method == "POST":

        if session.get("member_role") != "Administrateur":

            flash(
                "Seuls les administrateurs peuvent ajouter des ouvrages.",
                "error"
            )

            return redirect(
                url_for("library")
            )

        uploaded = request.files.get("file")

        title = request.form.get(
            "title",
            ""
        ).strip()

        author = request.form.get(
            "author",
            ""
        ).strip()

        category = request.form.get(
            "category",
            ""
        ).strip()

        description = request.form.get(
            "description",
            ""
        ).strip()

        access_grade = request.form.get(
            "access_grade",
            "Apprenti"
        ).strip()


        # =====================================================
        # VALIDATION DU GRADE
        # =====================================================

        allowed_grades = (
            "Apprenti",
            "Compagnon",
            "Maître",
            "Maître Secret",
            "Grand Elu, Parfait et Sublime Maçon",
            "Chevalier Rose-Croix",
            "CKS"
        )

        if access_grade not in allowed_grades:

            flash(
                "Niveau d'accès invalide.",
                "error"
            )

            return redirect(
                url_for("library")
            )


        # =====================================================
        # VALIDATION DU FICHIER
        # =====================================================

        if not uploaded or not uploaded.filename:

            flash(
                "Veuillez sélectionner un fichier.",
                "error"
            )

            return redirect(
                url_for("library")
            )

        original_name = secure_filename(
            uploaded.filename
        )

        if not original_name or "." not in original_name:

            flash(
                "Nom de fichier invalide.",
                "error"
            )

            return redirect(
                url_for("library")
            )

        extension = (
            original_name
            .rsplit(".", 1)[-1]
            .lower()
        )

        if extension not in ALLOWED_LIBRARY_EXTENSIONS:

            flash(
                "Format non autorisé. Utilisez uniquement PDF ou EPUB.",
                "error"
            )

            return redirect(
                url_for("library")
            )

        if not title or not category:

            flash(
                "Le titre et la catégorie sont obligatoires.",
                "error"
            )

            return redirect(
                url_for("library")
            )


        # =====================================================
        # ENREGISTREMENT DU FICHIER
        # =====================================================

        stored_name = (
            f"{uuid.uuid4().hex}.{extension}"
        )

        library_folder = (
            app.config["LIBRARY_FOLDER"]
        )

        library_folder.mkdir(
            parents=True,
            exist_ok=True
        )

        file_path = (
            library_folder
            / stored_name
        )

        uploaded.save(file_path)


        # =====================================================
        # ENREGISTREMENT EN BASE
        # =====================================================

        try:

            db().execute(
                """
                INSERT INTO library_items
                (
                    title,
                    author,
                    category,
                    description,
                    stored_name,
                    original_name,
                    file_extension,
                    access_grade
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    title,
                    author,
                    category,
                    description,
                    stored_name,
                    original_name,
                    extension,
                    access_grade
                )
            )

            db().commit()

        except Exception:

            db().rollback()

            if file_path.exists():
                file_path.unlink()

            raise


        flash(
            "Ouvrage ajouté à la bibliothèque privée.",
            "success"
        )

        return redirect(
            url_for("library")
        )


    # =====================================================
    # RECHERCHE DANS LA BIBLIOTHÈQUE
    # =====================================================

    search = request.args.get(
        "q",
        ""
    ).strip()


    if search:

        search_pattern = f"%{search}%"

        items = db().execute(
            """
            SELECT *
            FROM library_items
            WHERE
                title ILIKE %s
                OR author ILIKE %s
                OR category ILIKE %s
                OR description ILIKE %s
            ORDER BY added_at DESC
            """,
            (
                search_pattern,
                search_pattern,
                search_pattern,
                search_pattern
            )
        ).fetchall()

    else:

        items = db().execute(
            """
            SELECT *
            FROM library_items
            ORDER BY added_at DESC
            """
        ).fetchall()


    return render_template(
        "library.html",
        items=items,
        search=search
    )


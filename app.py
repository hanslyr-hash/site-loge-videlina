@app.route("/admin/actualites", methods=["GET", "POST"])
@login_required
@admin_required
def manage_news():

    database = db()

    if request.method == "POST":

        title = request.form.get(
            "title",
            ""
        ).strip()

        category = request.form.get(
            "category",
            ""
        ).strip()

        excerpt = request.form.get(
            "excerpt",
            ""
        ).strip()

        content = request.form.get(
            "content",
            ""
        ).strip()

        status = request.form.get(
            "status",
            "Brouillon"
        ).strip()

        if status not in ("Brouillon", "Publié"):
            status = "Brouillon"

        # =====================================================
        # VALIDATION
        # =====================================================

        if not title or not category or not content:

            flash(
                "Le titre, la catégorie et le contenu sont obligatoires.",
                "error"
            )

            return redirect(
                url_for("manage_news")
            )

        # =====================================================
        # IMAGE
        # =====================================================

        image = request.files.get("image")

        image_name = None
        image_path = None

        if image and image.filename:

            original_name = secure_filename(
                image.filename
            )

            if (
                not original_name
                or "." not in original_name
            ):

                flash(
                    "Nom de fichier image invalide.",
                    "error"
                )

                return redirect(
                    url_for("manage_news")
                )

            extension = (
                original_name
                .rsplit(".", 1)[-1]
                .lower()
            )

            if extension not in ALLOWED_NEWS_IMAGE_EXTENSIONS:

                flash(
                    "Format d'image non autorisé. "
                    "Utilisez JPG, JPEG, PNG ou WebP.",
                    "error"
                )

                return redirect(
                    url_for("manage_news")
                )

            image_name = (
                f"{uuid.uuid4().hex}.{extension}"
            )

            news_image_folder = (
                app.config["NEWS_IMAGE_FOLDER"]
            )

            news_image_folder.mkdir(
                parents=True,
                exist_ok=True
            )

            image_path = (
                news_image_folder
                / image_name
            )

            image.save(image_path)

        # =====================================================
        # PUBLICATION
        # =====================================================

        published_at = (
            datetime.now()
            if status == "Publié"
            else None
        )

        try:

            database.execute(
                """
                INSERT INTO news
                (
                    title,
                    category,
                    excerpt,
                    content,
                    image_name,
                    status,
                    published_at
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    title,
                    category,
                    excerpt,
                    content,
                    image_name,
                    status,
                    published_at
                )
            )

            database.commit()

        except Exception:

            database.rollback()

            if image_path and image_path.exists():
                image_path.unlink()

            raise

        flash(
            "Actualité enregistrée avec succès.",
            "success"
        )

        return redirect(
            url_for("manage_news")
        )

    # =====================================================
    # LISTE DES ACTUALITÉS
    # =====================================================

    news = database.execute(
        """
        SELECT *
        FROM news
        ORDER BY created_at DESC
        """
    ).fetchall()

    return render_template(
        "news_admin.html",
        news=news
    )


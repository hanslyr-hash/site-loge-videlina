@app.post("/contact")
def contact():

    name = request.form.get("name", "").strip()
    email = request.form.get("email", "").strip()
    subject = request.form.get("subject", "").strip()
    message = request.form.get("message", "").strip()


    # Vérification des champs obligatoires
    if not (name and email and subject and message):
        print("⚠️ Formulaire contact incomplet.")

        response = redirect(
            url_for(
                "home",
                contact_error="2",
                _anchor="contact"
            )
        )

        # Empêcher le navigateur de restaurer l'ancien formulaire
        response.headers["Cache-Control"] = "no-store, no-cache, must-revalidate, max-age=0"
        response.headers["Pragma"] = "no-cache"
        response.headers["Expires"] = "0"

        return response

    database = db()

    try:

        database.execute(
            """
            INSERT INTO contact_messages
                (name, email, subject, message)
            VALUES (%s, %s, %s, %s)
            """,
            (
                name,
                email,
                subject,
                message
            ),
        )

        database.commit()

        print("✅ Message visiteur enregistré dans Neon.")

        response = redirect(
            url_for(
                "home",
                contact_sent="1",
                _anchor="contact"
            )
        )

        # Très important :
        # empêcher le navigateur de restaurer
        # l'ancien contenu du formulaire.
        response.headers["Cache-Control"] = "no-store, no-cache, must-revalidate, max-age=0"
        response.headers["Pragma"] = "no-cache"
        response.headers["Expires"] = "0"

        return response

    except Exception as error:

        database.rollback()

        print(
            f"❌ Erreur enregistrement message visiteur : {error}"
        )

        response = redirect(
            url_for(
                "home",
                contact_error="1",
                _anchor="contact"
            )
        )

        response.headers["Cache-Control"] = "no-store, no-cache, must-revalidate, max-age=0"
        response.headers["Pragma"] = "no-cache"
        response.headers["Expires"] = "0"

        return response




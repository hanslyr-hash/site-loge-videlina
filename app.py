@app.route(
    "/admin/messages/<int:message_id>/repondre",
    methods=["GET", "POST"],
)
@login_required
@admin_required
def reply_contact_message(message_id):

    database = db()

    message = database.execute(
        """
        SELECT
            id,
            name,
            email,
            subject,
            message,
            is_read,
            created_at
        FROM contact_messages
        WHERE id = %s
        """,
        (message_id,),
    ).fetchone()

    if message is None:

        flash(
            "Message visiteur introuvable.",
            "error",
        )

        return redirect(
            url_for("manage_contact_messages")
        )

    if request.method == "POST":

        reply_message = request.form.get(
            "reply_message",
            "",
        ).strip()

        if not reply_message:

            flash(
                "La réponse ne peut pas être vide.",
                "error",
            )

            return render_template(
                "contact_message_reply.html",
                message=message,
            )

        try:

            resend.Emails.send(
                {
                    "from": os.getenv(
                        "MAIL_FROM",
                        "onboarding@resend.dev",
                    ),
                    "to": [message["email"]],
                    "subject": (
                        "Re: "
                        + message["subject"]
                    ),
                    "text": reply_message,
                }
            )

            database.execute(
                """
                UPDATE contact_messages
                SET
                    is_read = TRUE,
                    reply_message = %s,
                    replied_at = NOW()
                WHERE id = %s
                """,
                (
                    reply_message,
                    message_id,
                ),
            )


            database.commit()

            flash(
                "Réponse envoyée avec succès.",
                "success",
            )

            return redirect(
                url_for("manage_contact_messages")
            )

        except Exception as error:

            database.rollback()

            print(
                f"❌ Erreur envoi e-mail Resend : {error}"
            )

            flash(
                "Impossible d'envoyer la réponse.",
                "error",
            )

    return render_template(
        "contact_message_reply.html",
        message=message,
    )


@app.post(
    "/membres/<int:member_id>/statut"
)
@login_required
@admin_required
def toggle_member_status(member_id):

    database = db()

    member = database.execute(
        """
        SELECT id, status
        FROM members
        WHERE id = %s
        """,
        (member_id,),
    ).fetchone()

    if member is None:

        flash(
            "Membre introuvable.",
            "error",
        )

        return redirect(
            url_for("manage_members")
        )

    if member_id == session["member_id"]:

        flash(
            "Vous ne pouvez pas désactiver votre propre compte.",
            "error",
        )

        return redirect(
            url_for("manage_members")
        )

    new_status = (
        "Inactif"
        if member["status"] == "Actif"
        else "Actif"
    )

    database.execute(
        """
        UPDATE members
        SET status = %s
        WHERE id = %s
        """,
        (
            new_status,
            member_id,
        ),
    )

    database.commit()

    flash(
        "Statut du membre mis à jour.",
        "success",
    )

    return redirect(
        url_for("manage_members")
    )



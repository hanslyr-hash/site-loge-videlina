def db():

    if "db" not in g:

        database_url = os.getenv(
            "DATABASE_URL"
        )

        if database_url:

            g.db = psycopg.connect(
                database_url,
                row_factory=dict_row,
            )

        else:

            g.db = psycopg.connect(
                host=os.getenv(
                    "DB_HOST",
                    "localhost",
                ),

                port=os.getenv(
                    "DB_PORT",
                    "5432",
                ),

                dbname=os.getenv(
                    "DB_NAME",
                    "videlina_db",
                ),

                user=os.getenv(
                    "DB_USER",
                    "postgres",
                ),

                password=os.getenv(
                    "DB_PASSWORD",
                ),

                row_factory=dict_row,
            )

    return g.db



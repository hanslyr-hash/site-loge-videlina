@app.post(
    "/bibliotheque/supprimer/<int:item_id>"
)
@login_required
@admin_required
def delete_library_item(item_id):

    database = db()

    item = database.execute(
        """
        SELECT stored_name
        FROM library_items
        WHERE id = %s
        """,
        (item_id,),
    ).fetchone()

    if item is None:

        flash(
            "Ouvrage introuvable.",
            "error",
        )

        return redirect(
            url_for("library")
        )

    if not supabase_is_configured():

        flash(
            "Le stockage Supabase n'est pas configuré.",
            "error",
        )

        return redirect(
            url_for("library")
        )

    storage_url = get_storage_url(
        item["stored_name"]
    )

    try:

        response = httpx.delete(
            storage_url,
            headers=get_storage_headers(),
            timeout=60.0,
        )

        if response.status_code not in (
            200,
            204,
        ):

            app.logger.error(
                "Erreur suppression Supabase HTTP %s : %s",
                response.status_code,
                response.text[:500],
            )

            flash(
                "Impossible de supprimer le fichier de Supabase.",
                "error",
            )

            return redirect(
                url_for("library")
            )

        database.execute(
            """
            DELETE FROM library_items
            WHERE id = %s
            """,
            (item_id,),
        )

        database.commit()

        flash(
            "Ouvrage supprimé de la bibliothèque.",
            "success",
        )

    except Exception:

        database.rollback()

        app.logger.exception(
            "Erreur lors de la suppression de l'ouvrage."
        )

        flash(
            "Une erreur est survenue lors de la suppression.",
            "error",
        )

    return redirect(
        url_for("library")
    )



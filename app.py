@app.route(
    "/membres/gestion",
    methods=["GET", "POST"]
)
@login_required
@admin_required
def manage_members():

    database = db()

    if request.method == "POST":

        name = request.form.get(
            "name",
            "",
        ).strip()

        email = request.form.get(
            "email",
            "",
        ).strip().lower()

        role = request.form.get(
            "role",
            "Membre",
        ).strip()

        grade = request.form.get(
            "grade",
            "Apprenti",
        ).strip()

        password = request.form.get(
            "password",
            "",
        )

        if role not in ALLOWED_ROLES:
            role = "Membre"

        if grade not in ALLOWED_GRADES:
            grade = "Apprenti"

        if (
            not name
            or not email
            or len(password) < 8
        ):

            flash(
                "Indiquez le nom, l'e-mail et un mot de passe d'au moins 8 caractères.",
                "error",
            )

        else:

            try:

                database.execute(
                    """
                    INSERT INTO members
                    (
                        name,
                        email,
                        password_hash,
                        role,
                        grade,
                        status
                    )
                    VALUES (%s, %s, %s, %s, %s, %s)
                    """,
                    (
                        name,
                        email,
                        generate_password_hash(
                            password
                        ),
                        role,
                        grade,
                        "Actif",
                    ),
                )

                database.commit()

                flash(
                    "Membre ajouté avec succès.",
                    "success",
                )

            except UniqueViolation:

                database.rollback()

                flash(
                    "Cette adresse e-mail est déjà utilisée.",
                    "error",
                )

    search = request.args.get(
        "q",
        "",
    ).strip()

    if search:

        pattern = f"%{search}%"

        members = database.execute(
            """
            SELECT
                id,
                name,
                email,
                role,
                grade,
                status
            FROM members
            WHERE name ILIKE %s
               OR email ILIKE %s
            ORDER BY name
            """,
            (
                pattern,
                pattern,
            ),
        ).fetchall()

    else:

        members = database.execute(
            """
            SELECT
                id,
                name,
                email,
                role,
                grade,
                status
            FROM members
            ORDER BY name
            """
        ).fetchall()

    return render_template(
        "members.html",
        members=members,
        search=search,
    )



def login_required(view):

    @wraps(view)
    def wrapper(*args, **kwargs):

        if "member_id" not in session:

            flash(
                "Veuillez vous connecter.",
                "error",
            )

            return redirect(
                url_for("login")
            )

        return view(
            *args,
            **kwargs
        )

    return wrapper


def admin_required(view):

    @wraps(view)
    def wrapper(*args, **kwargs):

        if not is_admin():

            flash(
                "Action réservée aux administrateurs.",
                "error",
            )

            return redirect(
                url_for("dashboard")
            )

        return view(
            *args,
            **kwargs
        )

    return wrapper



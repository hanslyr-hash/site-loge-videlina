@app.route("/admin/actualites/modifier/<int:news_id>", methods=["GET", "POST"])
@login_required
@admin_required
def edit_news(news_id):

    database = db()

    item = database.execute(
        """
        SELECT *
        FROM news
        WHERE id = %s
        """,
        (news_id,)
    ).fetchone()

    if item is None:

        flash(
            "Actualité introuvable.",
            "error"
        )

        return redirect(url_for("manage_news"))

    if request.method == "POST":

        title = request.form.get(
            "title",
            ""
        ).strip()

        category = request.form.get(
            "category",
            ""
        ).strip()

        excerpt = request.form.get(
            "excerpt",
            ""
        ).strip()

        content = request.form.get(
            "content",
            ""
        ).strip()

        status = request.form.get(
            "status",
            "Brouillon"
        ).strip()

        if status not in ("Brouillon", "Publié"):
            status = "Brouillon"

        if not title or not category or not content:

            flash(
                "Le titre, la catégorie et le contenu sont obligatoires.",
                "error"
            )

            return redirect(
                url_for(
                    "edit_news",
                    news_id=news_id
                )
            )

        # -------------------------------------------------
        # GESTION DE LA PUBLICATION
        # -------------------------------------------------

        if status == "Publié":

            published_at = (
                item["published_at"]
                or datetime.now()
            )

        else:

            published_at = None

        # -------------------------------------------------
        # IMAGE
        # -------------------------------------------------

        image = request.files.get("image")

        new_image_name = item["image_name"]
        new_image_path = None

        if image and image.filename:

            original_name = secure_filename(
                image.filename
            )

            if (
                not original_name
                or "." not in original_name
            ):

                flash(
                    "Nom de fichier image invalide.",
                    "error"
                )

                return redirect(
                    url_for(
                        "edit_news",
                        news_id=news_id
                    )
                )

            extension = (
                original_name
                .rsplit(".", 1)[-1]
                .lower()
            )

            if extension not in ALLOWED_NEWS_IMAGE_EXTENSIONS:

                flash(
                    "Format d'image non autorisé. "
                    "Utilisez JPG, JPEG, PNG ou WebP.",
                    "error"
                )

                return redirect(
                    url_for(
                        "edit_news",
                        news_id=news_id
                    )
                )

            new_image_name = (
                f"{uuid.uuid4().hex}.{extension}"
            )

            news_image_folder = (
                app.config["NEWS_IMAGE_FOLDER"]
            )

            news_image_folder.mkdir(
                parents=True,
                exist_ok=True
            )

            new_image_path = (
                news_image_folder
                / new_image_name
            )

            image.save(new_image_path)

        # -------------------------------------------------
        # MISE À JOUR
        # -------------------------------------------------

        try:

            database.execute(
                """
                UPDATE news
                SET
                    title = %s,
                    category = %s,
                    excerpt = %s,
                    content = %s,
                    image_name = %s,
                    status = %s,
                    published_at = %s,
                    updated_at = CURRENT_TIMESTAMP
                WHERE id = %s
                """,
                (
                    title,
                    category,
                    excerpt,
                    content,
                    new_image_name,
                    status,
                    published_at,
                    news_id
                )
            )

            database.commit()

        except Exception:

            database.rollback()

            if new_image_path and new_image_path.exists():
                new_image_path.unlink()

            raise

        # -------------------------------------------------
        # SUPPRIMER L'ANCIENNE IMAGE
        # -------------------------------------------------

        if (
            new_image_path
            and item["image_name"]
            and item["image_name"] != new_image_name
        ):

            old_image_path = (
                app.config["NEWS_IMAGE_FOLDER"]
                / item["image_name"]
            )

            if old_image_path.exists():
                old_image_path.unlink()

        flash(
            "Actualité modifiée avec succès.",
            "success"
        )

        return redirect(
            url_for("manage_news")
        )

    return render_template(
        "news_edit.html",
        item=item
    )


